/// Returns the BeginString (tag 8) value for a given FIX spec.
fn begin_string(spec: &str) -> &'static str {
    match spec {
        "FIX40" => "FIX.4.0",
        "FIX41" => "FIX.4.1",
        "FIX42" => "FIX.4.2",
        "FIX43" => "FIX.4.3",
        "FIX44" => "FIX.4.4",
        "FIX50" => "FIX.5.0",
        "FIXT11" => "FIXT.1.1",
        _ => "FIX.4.1",
    }
}

